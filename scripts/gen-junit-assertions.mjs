// Generates java/sandbox/org/junit/jupiter/api/Assertions.java, the small
// JUnit runner's Assertions class, from real JUnit's: every public static
// method with exactly the same signature (so any test that compiles against
// JUnit 5 compiles here), each delegating to AssertionSupport, which holds
// the semantics. Rerun after changing JUNIT_VERSION in fetch-junit.mjs;
// e2e/junit-runner.spec.ts checks the signatures still match.
//
//   node scripts/gen-junit-assertions.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fetchJunit } from "./fetch-junit.mjs";

const jar = await fetchJunit();
const javap = process.env.JAVA_HOME ? join(process.env.JAVA_HOME, "bin", "javap") : "javap";
const listing = execFileSync(javap, ["-cp", jar, "org.junit.jupiter.api.Assertions"], { encoding: "utf8" });

/** Splits a parameter list on top-level commas (not those inside <...>). */
function splitParams(text) {
  const parts = [];
  let depth = 0;
  let current = "";
  for (const ch of text) {
    if (ch === "<") depth++;
    if (ch === ">") depth--;
    if (ch === "," && depth === 0) {
      parts.push(current.trim());
      current = "";
    } else {
      current += ch;
    }
  }
  if (current.trim()) parts.push(current.trim());
  return parts;
}

const isMessage = (type) => type === "java.lang.String" || type === "java.util.function.Supplier<java.lang.String>";
const isDelta = (type) => type === "float" || type === "double";
const EQUALITY = new Set(["assertEquals", "assertNotEquals", "assertArrayEquals"]);

const methods = [];
for (const raw of listing.split("\n")) {
  const line = raw.trim();
  if (!line.startsWith("public static ")) continue;
  const m = /^public static (<.+?> )?(\S+) (\w+)\((.*)\)( throws [^;]+)?;$/.exec(line);
  if (!m) throw new Error(`Could not parse: ${line}`);
  const [, generics = "", returns, name, paramText, throwsClause = ""] = m;
  const types = splitParams(paramText).map((t) => t.replace(/\$/g, "."));
  methods.push({ generics: generics.replace(/\$/g, "."), returns, name, types, throwsClause });
}

function body({ name, returns, types }) {
  const names = types.map((_, i) => `p${i}`);
  const ret = returns === "void" ? "" : "return ";
  if (name === "fail") {
    // fail(), fail(message), fail(message, cause), fail(cause), fail(messageSupplier)
    const message = types.findIndex(isMessage);
    const cause = types.findIndex((t) => t === "java.lang.Throwable");
    return `throw AssertionSupport.fail(${message >= 0 ? names[message] : "null"}, ${cause >= 0 ? names[cause] : "null"});`;
  }
  if (EQUALITY.has(name)) {
    // (expected, actual[, delta][, message])
    const delta = types.length >= 3 && isDelta(types[2]) ? `Double.valueOf((double) ${names[2]})` : "null";
    const last = types.length - 1;
    const message = last >= 2 && isMessage(types[last]) ? names[last] : "null";
    return `AssertionSupport.${name}(${names[0]}, ${names[1]}, ${delta}, ${message});`;
  }
  if (name === "assertAll") {
    // ([heading,] executables)
    return types.length === 2 ? `AssertionSupport.assertAll(p0, p1);` : `AssertionSupport.assertAll((String) null, p0);`;
  }
  if (name === "assertTimeoutPreemptively" && types.length === 4) {
    return `return AssertionSupport.assertTimeoutPreemptively(p0, p1, p2, p3);`;
  }
  // Everything else: (arguments...[, message]) -> (arguments..., message or null)
  const last = types.length - 1;
  const hasMessage = last >= 1 && isMessage(types[last]);
  const args = hasMessage ? names : [...names, "null"];
  return `${ret}AssertionSupport.${name}(${args.join(", ")});`;
}

const out = [];
out.push(`// GENERATED by scripts/gen-junit-assertions.mjs from JUnit ${listing.match(/Compiled from/) ? "" : ""}Assertions; do not edit.
package org.junit.jupiter.api;

/**
 * JUnit 5's Assertions, for the small runner: every public static method of
 * the real class (generated from its signatures), with the semantics and
 * failure messages in AssertionSupport.
 */
public final class Assertions {
    private Assertions() {
    }

    /** As in JUnit: makes the failure assertTimeoutPreemptively throws. */
    @FunctionalInterface
    public interface TimeoutFailureFactory<T extends Throwable> {
        T createTimeoutFailure(java.time.Duration timeout, java.util.function.Supplier<String> messageSupplier,
                Throwable cause, Thread testThread);
    }
`);
for (const method of methods) {
  const params = method.types
    .map((type, i) => (type.endsWith("...") ? `${type} p${i}` : `${type} p${i}`))
    .join(", ");
  out.push(`    public static ${method.generics}${method.returns} ${method.name}(${params})${method.throwsClause} {`);
  out.push(`        ${body(method)}`);
  out.push(`    }`);
  out.push("");
}
out.push("}");
const file = join(process.cwd(), "java", "sandbox", "org", "junit", "jupiter", "api", "Assertions.java");
writeFileSync(file, out.join("\n") + "\n");
console.log(`${file}: ${methods.length} methods`);
